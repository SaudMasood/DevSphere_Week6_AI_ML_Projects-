attendance = np.random.uniform(40, 100, n)
previous_score = np.random.uniform(30, 100, n)

# Synthetic educational score used to generate demonstration labels.
# These are simulated data, not real student records.
performance_score = (
    4.0 * study_hours
    + 0.30 * attendance
    + 0.35 * previous_score
    + np.random.normal(0, 7, n)
)

passed = (performance_score >= 48).astype(int)

df = pd.DataFrame({
    "StudyHours": np.round(study_hours, 2),
    "Attendance": np.round(attendance, 2),
    "PreviousScore": np.round(previous_score, 2),
    "Passed": passed
})

