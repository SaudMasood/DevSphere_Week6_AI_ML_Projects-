from sklearn.model_selection import train_test_split
from sklearn.pipeline import Pipeline
from sklearn.impute import SimpleImputer

from sklearn.linear_model import LinearRegression
from sklearn.tree import DecisionTreeRegressor
from sklearn.ensemble import RandomForestRegressor

from sklearn.metrics import (
    mean_absolute_error,
    mean_squared_error,
    r2_score
)

# ================================================================
# 1. PROJECT HEADER
# ================================================================

print("=" * 70)
print("        DEVSPHERE INTERNSHIP - WEEK 6 FINAL PROJECT")
print("              HOUSE PRICE PREDICTION SYSTEM")
print("=" * 70)

print("Developer: Saud Masood")
print("Domain: Machine Learning")
print("Task: Complete ML Prediction Project")


# ================================================================
# 2. CREATE DATASET
# ================================================================

print("\n[1/7] Creating house price dataset...")

np.random.seed(42)

number_of_houses = 800

area = np.random.randint(500, 4001, number_of_houses)
bedrooms = np.random.randint(1, 7, number_of_houses)
bathrooms = np.random.randint(1, 5, number_of_houses)
house_age = np.random.randint(0, 41, number_of_houses)
distance = np.random.uniform(1, 30, number_of_houses)

# Generate synthetic prices for educational demonstration.
# Prices are illustrative, not actual market valuations.

noise = np.random.normal(0, 12000, number_of_houses)

price = (
    25000
    + area * 110
    + bedrooms * 9000
    + bathrooms * 12000
    - house_age * 850
    - distance * 1200
    + noise
)

price = np.maximum(price, 30000)

df = pd.DataFrame({
    "Area_sqft": area,
    "Bedrooms": bedrooms,
    "Bathrooms": bathrooms,
    "HouseAge": house_age,
    "Distance_km": np.round(distance, 2),
    "Price": np.round(price, 2)
})

# Introduce a few missing feature values to demonstrate preprocessing.
for column in [
    "Area_sqft",
    "Bedrooms",
    "Bathrooms",
    "HouseAge",
    "Distance_km"
]:
    missing_indices = df.sample(
        frac=0.02, random_state=42
    ).index

    df.loc[missing_indices, column] = np.nan

df.to_csv("house_prices_week6.csv", index=False)

print("\nDataset created successfully!")
print("Dataset shape:", df.shape)

print("\nFirst 10 rows:")
print(df.head(10))

print("\nDataset information:")
df.info()

print("\nStatistical summary:")
print(df.describe().round(2))

print("\nMissing values:")
print(df.isnull().sum())


# ================================================================
# 3. DATA PREPROCESSING
# ================================================================

print("\n[2/7] Preprocessing dataset...")

# Remove duplicate rows.
df = df.drop_duplicates().reset_index(drop=True)

# Separate input features and target.
X = df.drop(columns=["Price"])
y = df["Price"]

# Split before fitting the preprocessing pipeline to prevent
# information from the test set leaking into training.
X_train, X_test, y_train, y_test = train_test_split(
    X,
    y,
    test_size=0.20,
    random_state=42
)

print("Training samples:", len(X_train))
print("Testing samples:", len(X_test))
print("Duplicates removed.")
print("Missing numerical features will be filled using medians.")
print("Data preprocessing completed!")


# ================================================================
# 4. TRAIN MULTIPLE REGRESSION MODELS
# ================================================================

print("\n[3/7] Training machine learning models...")

models = {
    "Linear Regression": Pipeline([
        ("imputer", SimpleImputer(strategy="median")),
        ("model", LinearRegression())
    ]),

    "Decision Tree": Pipeline([
        ("imputer", SimpleImputer(strategy="median")),
        ("model", DecisionTreeRegressor(
            max_depth=12,
            random_state=42
        ))
    ]),

    "Random Forest": Pipeline([
        ("imputer", SimpleImputer(strategy="median")),
        ("model", RandomForestRegressor(
            n_estimators=150,
            random_state=42,
            n_jobs=-1
        ))
    ])
}

results = []
trained_models = {}

for name, model in models.items():

    model.fit(X_train, y_train)

    predictions = model.predict(X_test)

    mae = mean_absolute_error(y_test, predictions)
    mse = mean_squared_error(y_test, predictions)
    rmse = np.sqrt(mse)
    r2 = r2_score(y_test, predictions)

    trained_models[name] = model

    results.append({
        "Model": name,
        "MAE": mae,
        "MSE": mse,
        "RMSE": rmse,
        "R2 Score": r2
    })

    print(f"\n{name} trained successfully!")
    print(f"MAE:  {mae:,.2f}")
    print(f"RMSE: {rmse:,.2f}")
    print(f"R2 Score: {r2:.4f}")


# ================================================================
# 5. MODEL EVALUATION AND COMPARISON
# ================================================================

print("\n[4/7] Comparing model performance...")

results_df = pd.DataFrame(results)

print("\nModel Comparison:")
print(results_df.round(4).to_string(index=False))

# Select the model with the lowest test RMSE.
best_model_name = results_df.loc[
    results_df["RMSE"].idxmin(),
    "Model"
]

best_model = trained_models[best_model_name]

best_predictions = best_model.predict(X_test)

print("\nBest model based on test RMSE:", best_model_name)

print("\nBest Model Evaluation:")
print(f"MAE: {mean_absolute_error(y_test, best_predictions):,.2f}")
print(f"RMSE: {np.sqrt(mean_squared_error(y_test, best_predictions)):,.2f}")
print(f"R2 Score: {r2_score(y_test, best_predictions):.4f}")


